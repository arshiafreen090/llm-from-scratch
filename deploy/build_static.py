"""
Build the static website: the chat UI with the model running in the visitor's browser.

    python -m deploy.build_static                  # model files loaded from the Hugging Face model repo
    python -m deploy.build_static --local          # model files copied in (to test offline)
    python -m http.server -d build/site 8080       # try it at http://localhost:8080

The output is plain files (HTML, CSS, JavaScript, plus the model with --local), so any static
host works: a Hugging Face static Space (free), GitHub Pages, Netlify, ... The page is the
same one the FastAPI server serves (serve/web/); only config.js changes, to "browser" mode.

Before building, export the model once:
    python -m inference.export_onnx --ckpt checkpoints/sft-small-llama-s1-int8.pt
"""

import argparse
import json
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "serve", "web")
PAGE_FILES = ["style.css", "app.js", "tokenizer.js", "engine.js"]


def build(out, hf_repo, model, local):
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "static"))
    shutil.copy(os.path.join(WEB, "index.html"), os.path.join(out, "index.html"))
    for name in PAGE_FILES:
        shutil.copy(os.path.join(WEB, name), os.path.join(out, "static", name))

    if local:
        os.makedirs(os.path.join(out, "models"))
        for src in (f"checkpoints/{model}.onnx", f"checkpoints/{model}.onnx.json", "tokenizer/tinystories_4k.json"):
            shutil.copy(os.path.join(ROOT, src), os.path.join(out, "models", os.path.basename(src)))
        base = "models/"
    else:
        base = f"https://huggingface.co/{hf_repo}/resolve/main/"
    config = {"mode": "browser", "modelUrl": f"{base}{model}.onnx", "metaUrl": f"{base}{model}.onnx.json",
              "tokenizerUrl": f"{base}tinystories_4k.json"}
    with open(os.path.join(out, "static", "config.js"), "w") as f:
        f.write("// Generated by deploy/build_static.py: the model runs in this browser (static/engine.js)\n")
        f.write(f"window.TL_CONFIG = {json.dumps(config, indent=2)};\n")

    # Hugging Face static Space settings (harmless on other hosts)
    shutil.copy(os.path.join(ROOT, "deploy", "huggingface-static", "README.md"), os.path.join(out, "README.md"))
    return config


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="build/site")
    parser.add_argument("--hf_repo", default="afeening/tinyllama-from-scratch", help="where the model files live")
    parser.add_argument("--model", default="sft-small-llama-s1-int8", help="name of the exported .onnx (no extension)")
    parser.add_argument("--local", action="store_true", help="copy the model files in instead of linking them")
    args = parser.parse_args()
    config = build(args.out, args.hf_repo, args.model, args.local)
    files = sum(len(fs) for _, _, fs in os.walk(args.out))
    print(f"built {args.out} ({files} files); model from {config['modelUrl']}")


if __name__ == "__main__":
    main()
